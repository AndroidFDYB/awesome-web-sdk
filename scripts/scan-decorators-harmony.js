/**
 * 鸿蒙端装饰器扫描脚本
 *
 * 扫描 entry 模块的 .ets 源文件，查找使用 @NeedsDataSync / @NeedsUserInfo /
 * @NeedsLoanInfo / @NeedsVipInfo 装饰器的页面/组件，生成 DataSyncBindings.ets。
 *
 * 对标 Android KSP 的编译期注解处理，在构建前自动生成静态绑定注册表。
 *
 * 用法：
 *   node scripts/scan-decorators-harmony.js
 *
 * 输出：
 *   hm/hm_web_library/src/main/ets/generated/DataSyncBindings.ets
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');

// 扫描目录：entry 模块的页面目录
const SCAN_DIRS = [
  path.join(ROOT, 'hm', 'entry', 'src', 'main', 'ets'),
];

// 输出路径
const OUTPUT_FILE = path.join(
  ROOT, 'hm', 'hm_web_library', 'src', 'main', 'ets', 'generated', 'DataSyncBindings.ets'
);

// ========================
// 通道名映射（与 proto codegen 保持一致）
// ========================

/** 标准快捷装饰器 → 通道名 */
const SHORTCUT_DECORATORS = {
  NeedsUserInfo: 'userInfo',
  NeedsLoanInfo: 'loanInfo',
  NeedsVipInfo: 'vipInfo',
};

/** DataSyncChannel.USER_INFO → 'userInfo' 映射 */
const CHANNEL_CONSTANTS = {
  'DataSyncChannel.USER_INFO': "'userInfo'",
  'DataSyncChannel.LOAN_INFO': "'loanInfo'",
  'DataSyncChannel.VIP_INFO': "'vipInfo'",
};

// ========================
// 文件扫描
// ========================

/**
 * 递归收集指定目录下的 .ets 文件
 */
function collectEtsFiles(dir) {
  const files = [];
  if (!fs.existsSync(dir)) return files;

  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...collectEtsFiles(fullPath));
    } else if (entry.name.endsWith('.ets')) {
      files.push(fullPath);
    }
  }
  return files;
}

// ========================
// 装饰器解析
// ========================

/**
 * 从 .ets 文件内容中解析装饰器和类名
 *
 * 支持的模式：
 * 1. @NeedsDataSync([DataSyncChannel.USER_INFO, DataSyncChannel.LOAN_INFO])
 * 2. @NeedsUserInfo
 * 3. @NeedsLoanInfo
 * 4. @NeedsVipInfo
 * 5. 多装饰器叠加（自动合并通道）
 *
 * @param {string} content .ets 文件内容
 * @param {string} filePath 文件路径（用于日志）
 * @returns {Array<{className: string, channels: string[]}>}
 */
function parseDecorators(content, filePath) {
  const results = [];
  const lines = content.split('\n');

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();

    // 检查是否是 struct/class 声明
    const structMatch = line.match(/^(?:export\s+)?(?:struct|class)\s+(\w+)/);
    if (!structMatch) continue;

    const className = structMatch[1];
    const channels = [];

    // 向上查找装饰器（最多 10 行）
    for (let j = i - 1; j >= Math.max(0, i - 10); j--) {
      const decLine = lines[j].trim();

      // 如果遇到另一个 struct/class/装饰器链以外的内容，停止
      if (decLine.match(/^(?:export\s+)?(?:struct|class|function|const|let|import)\s/)) {
        break;
      }

      // 匹配 @NeedsDataSync([DataSyncChannel.USER_INFO, ...])
      const needsDataSyncMatch = decLine.match(
        /@NeedsDataSync\s*\(\s*\[([^\]]*)\]\s*\)/
      );
      if (needsDataSyncMatch) {
        const argsStr = needsDataSyncMatch[1];
        // 解析 DataSyncChannel.XXX 常量引用
        const constRefs = argsStr.match(/DataSyncChannel\.\w+/g) || [];
        for (const ref of constRefs) {
          const channelValue = CHANNEL_CONSTANTS[ref];
          if (channelValue) {
            // 使用不带引号的原始值
            channels.push(channelValue.replace(/'/g, ''));
          }
        }
        // 也支持字符串字面量 'xxx' 或 "xxx"
        const strLiterals = argsStr.match(/['"](\w+)['"]/g) || [];
        for (const lit of strLiterals) {
          channels.push(lit.replace(/['"]/g, ''));
        }
        continue;
      }

      // 匹配快捷装饰器 @NeedsUserInfo / @NeedsLoanInfo / @NeedsVipInfo
      for (const [decorator, channel] of Object.entries(SHORTCUT_DECORATORS)) {
        if (decLine.includes(`@${decorator}`)) {
          channels.push(channel);
        }
      }
    }

    // 去重
    const uniqueChannels = [...new Set(channels)];

    if (uniqueChannels.length > 0) {
      results.push({ className, channels: uniqueChannels });
      console.log(`[ScanDecorators/Harmony] ${path.basename(filePath)}: ${className} → [${uniqueChannels.join(', ')}]`);
    }
  }

  return results;
}

// ========================
// 代码生成
// ========================

/**
 * 生成 DataSyncBindings.ets 文件内容
 *
 * @param {Array<{className: string, channels: string[]}>} bindings 绑定列表
 * @returns {string}
 */
function generateBindingsCode(bindings) {
  // 生成 switch cases
  const switchCases = bindings
    .map(({ className, channels }) => {
      const channelValues = channels.map(ch => `DataSyncChannel.${toUpperSnakeCase(ch)}`).join(', ');
      return `      case '${className}':\n        return [${channelValues}];`;
    })
    .join('\n');

  // 生成类名列表
  const classNames = bindings.map(b => `'${b.className}'`).join(', ');

  return `// AUTO-GENERATED by scan-decorators-harmony.js. DO NOT EDIT.
//
// 静态数据通道绑定注册表
//
// 由构建工具扫描使用 @NeedsDataSync / @NeedsUserInfo 等装饰器的页面后自动生成。
// DataSyncHelper.create() 优先从此表查表，实现编译期确定通道列表。
//
// 生成方式：
//   1. hvigor 插件（编译期自动触发）
//   2. node scripts/scan-decorators-harmony.js（手动执行）
//
// 运行时回退：
//   如果某个类未在此注册表中，DataSyncHelper.create() 会回退到
//   DecoratorRegistry 运行时注册表查询。

import { DataSyncChannel } from './DataSyncChannels';

/**
 * 静态数据通道绑定注册表
 *
 * 映射：页面/组件类名 → 所需数据通道数组
 * 由构建工具自动生成，开发者无需手动维护。
 */
export class DataSyncBindings {
  /**
   * 根据类名获取所需的数据通道列表
   *
   * @param className 页面/组件的类名（如 'LoanPage'）
   * @returns 所需通道数组，未注册时返回空数组
   *
   * @example
   * \`\`\`typescript
   * const channels = DataSyncBindings.getChannels('LoanPage');
   * // => ['userInfo', 'loanInfo']
   * \`\`\`
   */
  static getChannels(className: string): string[] {
    switch (className) {
${switchCases}
      default:
        return [];
    }
  }

  /**
   * 检查指定类名是否已注册
   */
  static hasBinding(className: string): boolean {
    return DataSyncBindings.getChannels(className).length > 0;
  }

  /**
   * 获取所有已注册的类名
   */
  static getRegisteredClasses(): string[] {
    return [${classNames}];
  }
}
`;
}

/**
 * camelCase → UPPER_SNAKE_CASE
 * userInfo → USER_INFO, loanInfo → LOAN_INFO
 */
function toUpperSnakeCase(camelCase) {
  let result = '';
  for (let i = 0; i < camelCase.length; i++) {
    const c = camelCase[i];
    if (i > 0 && c >= 'A' && c <= 'Z') {
      result += '_';
    }
    result += c.toUpperCase();
  }
  return result;
}

// ========================
// 主流程
// ========================

function run() {
  console.log('[ScanDecorators/Harmony] Scanning .ets files for @NeedsDataSync decorators...');

  // 1. 收集所有 .ets 文件
  const allFiles = [];
  for (const dir of SCAN_DIRS) {
    const files = collectEtsFiles(dir);
    allFiles.push(...files);
    console.log(`[ScanDecorators/Harmony] Found ${files.length} .ets files in ${dir}`);
  }

  // 2. 解析装饰器
  const allBindings = [];
  for (const file of allFiles) {
    const content = fs.readFileSync(file, 'utf-8');
    const bindings = parseDecorators(content, file);
    allBindings.push(...bindings);
  }

  if (allBindings.length === 0) {
    console.log('[ScanDecorators/Harmony] No @NeedsDataSync decorators found. Generating empty bindings.');
  } else {
    console.log(`[ScanDecorators/Harmony] Found ${allBindings.length} decorated classes.`);
  }

  // 3. 生成 DataSyncBindings.ets
  const code = generateBindingsCode(allBindings);

  // 确保输出目录存在
  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
  fs.writeFileSync(OUTPUT_FILE, code, 'utf-8');
  console.log(`[ScanDecorators/Harmony] Generated ${OUTPUT_FILE}`);
  console.log('[ScanDecorators/Harmony] Done.');
}

run();
